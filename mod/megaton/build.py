"""Build the Megaton mod for Fallout 2.

    python3 mod/megaton/build.py [--out DIR] [--stage FILE.py] [--only a,b] [step ...]   (default: all native build steps)

Steps
    ids      write scripts/ids.h (script numbers, GVARs, item PIDs, map/area ids) and
             scripts/tiles.h (named map spots) from registry.py and layout/spots.py
    data     stage the edited game tables (maps.txt, city.txt, scripts.lst, *.msg, quests)
             and the world map's MEGATON plate (art/intrface, worldmap_art.py)
    protos   create the mod's new item protos (protos.py)
    art      stage the custom pre-rendered art of mod/megaton-art (sprites, scenery and wall
             protos; its list and message additions are merged into the staged copies)
    scripts  compile with the pinned compiler, or copy verified production prebuilts;
             stage the current dialogue .msg files
    maps     generate the .map files (layout/, or the module given with --stage)
    lint     check the staged tables the way the engine parses them
    pack     write out/patch001.dat (the form the game loads)
    web      unavailable: browser hosting is not distributed in this repository

The art step copies the prepared mod/megaton-art/out tree, numbered by manifest.json.
Player setup restores committed own sprites and composes game-derived tiles locally.
Blender rendering is a separate author operation; see docs/testing.md. The generated
patch001.dat contains the native mod and stays outside the source repository.

Everything is staged under mod/megaton/out/ (or --out DIR, so several people
can build test variants side by side) using the game's own lower-case paths.
--only limits the scripts step to the listed script stems (someone else's
half-written script then cannot break your build). The mod ships as
patch001.dat because the engine searches patchNNN.dat archives before the
loose data/ folder, and patch000.dat already contains maps.txt, city.txt,
scripts.lst and friends: loose copies would be ignored.

--stage FILE.py replaces the real town with a small test map (stagekit.py
builds one in a single call). The stage file must define build_maps(out_dir),
which writes maps/megaton.map there, and may define two more names:

    SPOTS = {name: (hx, hy, rotation)}   spots the stage moved (stagekit.compact());
                                         every script is then compiled with matching
                                         TILE_<name> / ROT_<name> values instead of tiles.h's
    SCRIPTS_DIR = "scripts"              directory (relative to the stage file) searched
                                         for <stem>.ssl / <stem>.msg BEFORE scripts/: stand-ins
                                         for scripts that are not written yet, or test rigs

Easiest way to build and run a test: python3 mod/megaton/test.py -h
"""
