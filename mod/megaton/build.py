def config_read(path):
    """INI reader with the engine's quirks (configParseLine)."""
    cfg = {}
    last = "unknown"
    with open(path, "rb") as f:
        raw_lines = f.read().split(b"\n")
    for raw in raw_lines:
        s = raw.decode("latin-1")
        if len(s) > 255:
            print("lint: WARN line longer than the engine's 256-char buffer:", s[:40])
        i = s.find(";")
        if i >= 0:
            s = s[:i]
        s = s.lstrip()
        if s.startswith("["):
            j = s.find("]", 1)
            if j >= 0:
                last = s[1:j].strip()
                continue
        if "=" not in s:
            continue
        key, value = s.split("=", 1)
        cfg.setdefault(last.lower(), {})[key.strip().lower()] = value.strip()
    return cfg


def token(s):
    s = s.lstrip(" ")
    i = s.find(",")
    return (s, "") if i < 0 else (s[:i], s[i + 1:])


def step_lint():
    """Emulates wmMapInit / wmAreaInit: a typo in these tables stops the game at startup."""
    ok = True
    maps_cfg = config_read(os.path.join(OUT, "data", "maps.txt"))
    maps = []
    while True:
        section = maps_cfg.get("map %03d" % len(maps))
        if not section or "lookup_name" not in section:
            break
        index = len(maps)
        if "map_name" not in section:
            print(f"lint: FATAL Map {index:03d} has no map_name")
            ok = False
        if len(section["lookup_name"]) > 39 or len(section.get("map_name", "")) > 8:
            print(f"lint: ERR Map {index:03d} name too long")
            ok = False
        for key in ("saved", "dead_bodies_age", "pipboy_active", "automap"):
            if key in section and token(section[key])[0].lower() not in ("yes", "no"):
                print(f"lint: FATAL Map {index:03d} {key}={section[key]!r} is not yes/no")
                ok = False
        maps.append(section)
    if len(maps) > AUTOMAP_MAP_COUNT:
        print(f"lint: ERR more than {AUTOMAP_MAP_COUNT} maps (automap tables overflow)")
        ok = False
    for index, lookup, stem, _, _ in registry.MAPS:
        if index >= len(maps) or maps[index]["lookup_name"] != lookup or maps[index].get("map_name") != stem:
            print(f"lint: ERR Map {index:03d} is not {lookup}/{stem} after parsing (gap or wrong order?)")
            ok = False

    lookup = {}
    for index, section in enumerate(maps):
        lookup.setdefault(section["lookup_name"].lower(), index)

    city_cfg = config_read(os.path.join(OUT, "data", "city.txt"))
    areas = 0
    while areas < 5000:
        section = city_cfg.get("area %02d" % areas)
        if not section or "townmap_art_idx" not in section:
            break
        for required in ("area_name", "world_pos", "start_state", "size"):
            if required not in section:
                print(f"lint: FATAL Area {areas:02d} is missing {required}")
                ok = False
        if token(section.get("start_state", ""))[0].lower() not in ("on", "off"):
            print(f"lint: FATAL Area {areas:02d} start_state")
            ok = False
        if token(section.get("size", ""))[0].lower() not in ("small", "medium", "large"):
            print(f"lint: FATAL Area {areas:02d} size")
            ok = False
        entrance = 0
        while entrance < 10 and f"entrance_{entrance}" in section:
            rest = section[f"entrance_{entrance}"]
            state, rest = token(rest)
            _, rest = token(rest)
            _, rest = token(rest)
            name, rest = token(rest)
            if state.lower() not in ("on", "off"):
                print(f"lint: FATAL Area {areas:02d} entrance_{entrance} state {state!r}")
                ok = False
            if name.lower() not in lookup:
                print(f"lint: FATAL Area {areas:02d} entrance_{entrance}: map {name!r} is not in maps.txt (game will not start)")
                ok = False
            entrance += 1
        if entrance == 0:
            print(f"lint: ERR Area {areas:02d} has no entrance_0")
            ok = False
        areas += 1
    if areas != CITY_COUNT:
        print(f"lint: FATAL {areas} areas, the engine requires exactly {CITY_COUNT}")
        ok = False

    # intrface.lst: the label the staged city.txt points at must be our plate, and the file must be there.
    art_lst = open(os.path.join(OUT, "art", "intrface", "intrface.lst"), "rb").read().decode("latin-1").replace("\r\n", "\n").rstrip("\n").split("\n")
    megaton_area = city_cfg.get("area %02d" % registry.AREA, {})
    for name, index in interface_art_ids().items():
        if index >= len(art_lst) or not art_lst[index].lower().startswith(name) or not os.path.exists(os.path.join(OUT, "art", "intrface", name)):
            print(f"lint: ERR art/intrface/intrface.lst line {index} is not {name}, or the file is missing")
            ok = False
    label_index = megaton_area.get("townmap_label_art_idx", "-1")
    if not label_index.isdigit() or int(label_index) >= len(art_lst):
        print(f"lint: ERR Area {registry.AREA:02d} townmap_label_art_idx={label_index} is not a line of intrface.lst")
        ok = False

    # scripts.lst: every registered script must sit on the line its id says.
    lst = open(os.path.join(OUT, "scripts", "scripts.lst"), "rb").read().decode("latin-1").replace("\r\n", "\n").rstrip("\n").split("\n")
    for stem, (index, _) in script_ids().items():
        if index >= len(lst) or not lst[index].lower().startswith(stem + ".int"):
            print(f"lint: ERR scripts.lst line {index} is not {stem}.int")
            ok = False

    # Message files: a stray brace silently swallows every later line of the file.
    from f2lib import msg as msgfile  # tools/f2lib

    dialog_dir = os.path.join(OUT, "text", "english", "dialog")
    dialogs = sorted(os.listdir(dialog_dir)) if os.path.isdir(dialog_dir) else []
    for name in dialogs:
        try:
            with open(os.path.join(dialog_dir, name), "rb") as f:
                msgfile.parse(f.read())
        except ValueError as problem:
            print(f"lint: ERR text/english/dialog/{name}: {problem}")
            ok = False

    # Spots: scripts get them as tile numbers, the engine can only centre on part of the grid.
    from layout import spots

    for name, (hx, hy, rotation) in spots.SPOTS.items():
        if not (0 <= hx < 200 and 0 <= hy < 200 and 0 <= rotation < 6):
            print(f"lint: ERR spot {name} = ({hx}, {hy}, {rotation}) is not on the hex grid")
            ok = False

    gvars = list(registry.GVARS.values())
    if len(set(gvars)) != len(gvars) or any(not 634 <= g <= 692 for g in gvars):
        print("lint: ERR GVARs must be unique and inside the reserved block 634..692")
        ok = False

    flags = list(registry.FLAGS.values())
    if len(set(flags)) != len(flags) or any(f <= 0 or f & (f - 1) or f >= 1 << 31 for f in flags):
        print("lint: ERR MG_F_* flags must be distinct single bits below 1 << 31")
        ok = False
    stems = [stem for stem, _, _ in registry.SCRIPTS]
    if len(set(stems)) != len(stems) or any(len(stem) > 8 or not stem.startswith("mg") and stem != "megaton" for stem in stems):
        print("lint: ERR script stems must be unique, at most 8 characters and start with mg")
        ok = False

    art_staged = os.path.exists(os.path.join(OUT, "proto", "scenery", "scenery.lst"))
    if art_staged and not lint_art():
        ok = False

    print(f"lint: {len(maps)} maps, {areas} areas, {len(lst)} scripts, {len(dialogs)} dialogue files"
          + (", custom art" if art_staged else "") + f" -> {'OK' if ok else 'BROKEN'}")
    if not ok:
        raise SystemExit(1)


def staged_files():
    """{game path (lower-case, forward slashes): absolute file} for everything staged."""
    files = {}
    for base, _, names in os.walk(OUT):
        for name in names:
            full = os.path.join(base, name)
            rel = os.path.relpath(full, OUT).replace(os.sep, "/")
            if rel.endswith(".dat") or name.startswith("."):
                continue
            files[rel.lower()] = full
    return files


